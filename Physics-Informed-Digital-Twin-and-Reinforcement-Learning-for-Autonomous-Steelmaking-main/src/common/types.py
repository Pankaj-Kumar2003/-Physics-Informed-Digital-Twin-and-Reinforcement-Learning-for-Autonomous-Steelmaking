from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Tuple


@dataclass
class ProcessState:
    """Thermodynamic snapshot consumed by optimizers and RL."""

    time_step: int
    temperature_c: float
    composition_pct: Dict[str, float]
    slag_state: Dict[str, float]
    cumulative_alloy_cost: float = 0.0


@dataclass
class AlloyAction:
    """Structured action specifying alloy additions."""

    name: str
    mass_kg: float
    injection_route: str = "bulk"


@dataclass
class OptimizationResult:
    """Captures the static alloying plan produced by NSGA-II/Bayesian optimization."""

    pareto_front: List[Dict[str, float]]
    recommended_plan: List[AlloyAction]
    metrics: Dict[str, float]


@dataclass
class TwinBatch:
    """Container for synthetic rollouts generated by the digital twin."""

    states: List[ProcessState]
    actions: List[AlloyAction]
    targets: Dict[str, List[float]]
    metadata: Dict[str, str] = field(default_factory=dict)


@dataclass
class RewardBreakdown:
    """Decomposes RL reward for easier debugging."""

    grade_hit: float
    alloy_cost: float
    temperature_penalty: float
    emission_penalty: float


@dataclass
class OrchestratorArtifacts:
    """Paths to the trained assets consumed during orchestration."""

    piml_checkpoint: str
    optimizer_plan: str
    rl_policy: str
    config_path: str
